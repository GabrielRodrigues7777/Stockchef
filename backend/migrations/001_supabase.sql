CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo VARCHAR(40) CHECK (tipo IN ('Administrador','Funcionario')) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,


    codigo_estabelecimento VARCHAR(10) UNIQUE,


    id_estabelecimento INT,


    status VARCHAR(40) CHECK (status IN ('Pendente','Aprovado','Recusado')) NOT NULL DEFAULT 'Aprovado',


    camera_autorizada BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuarios_estabelecimento
        FOREIGN KEY (id_estabelecimento) REFERENCES usuarios(id_usuario)
);



CREATE TABLE categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(80) NOT NULL,
    descricao VARCHAR(255),
    PRIMARY KEY (id_categoria)
);


CREATE TABLE unidades_medida (
    id_unidade INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sigla VARCHAR(10) NOT NULL,
    descricao VARCHAR(60) NOT NULL,
    PRIMARY KEY (id_unidade)
);


CREATE TABLE produtos (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario INT NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    codigo_barras VARCHAR(100),
    qr_code VARCHAR(255),
    id_categoria INT NOT NULL,
    id_unidade INT NOT NULL,
    estoque_minimo DECIMAL(10,2) NOT NULL DEFAULT 0,
    imagem VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_produto)
);


CREATE TABLE lotes (
    id_lote INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_produto INT NOT NULL,
    numero_lote VARCHAR(60),
    validade DATE NOT NULL,
    quantidade_inicial DECIMAL(10,2) NOT NULL,
    quantidade_atual DECIMAL(10,2) NOT NULL,
    custo_unitario DECIMAL(10,2),
    data_entrada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    observacao TEXT,
    PRIMARY KEY (id_lote)
);


CREATE TABLE movimentacoes (
