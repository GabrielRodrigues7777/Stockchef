    status VARCHAR(40) CHECK (status IN ('Sucesso','Erro')) NOT NULL,
    resposta TEXT,
    data_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_historico_envio)
);




